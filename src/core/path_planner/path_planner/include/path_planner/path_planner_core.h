#ifndef RMP_PATH_PLANNER_PATH_PLANNER_NODE_H_
#define RMP_PATH_PLANNER_PATH_PLANNER_NODE_H_

#include <memory>

#include <rclcpp/rclcpp.hpp>
#include <geometry_msgs/msg/pose_stamped.hpp>
#include <nav_msgs/srv/get_plan.hpp>
#include <nav_msgs/msg/path.hpp>
#include <nav_msgs/msg/occupancy_grid.hpp>
#include <visualization_msgs/msg/marker.hpp>

#include "common/geometry/point.h"
#include "path_planner/path_planner.h"
#include "path_planner/utils/path_planner_factory.h"

namespace rmp
{
namespace path_planner
{
class PathPlannerCore
{
public:
  /**
   * @brief Construct a new Path Planner object
   */
  PathPlannerCore();

  /**
   * @brief Construct a new Path Planner object
   * @param node        ROS node
   * @param name        planner name
   * @param costmap_ros the cost map to use for assigning costs to trajectories
   */
  PathPlannerCore(rclcpp::Node::SharedPtr node, std::string name, nav2_costmap_2d::Costmap2DROS* costmap_ros);

  /**
   * @brief Destroy the Path Planner object
   */
  ~PathPlannerCore() = default;

  /**
   * @brief Planner initialization
   * @param node       ROS node
   * @param name       planner name
   * @param costmapRos costmap ROS wrapper
   */
  void initialize(rclcpp::Node::SharedPtr node, std::string name, nav2_costmap_2d::Costmap2DROS* costmapRos);

  /**
   * @brief Planner initialization
   * @param name planner name
   */
  void initialize(std::string name);

  /**
   * @brief Plan a path given start and goal in world map
   * @param start start in world map
   * @param goal  goal in world map
   * @param plan  plan
   * @return true if find a path successfully, else false
   */
  bool makePlan(const rmp::common::geometry::Point3d& start, const rmp::common::geometry::Point3d& goal,
                rmp::common::geometry::Points3d& plan);

  /**
   * @brief Plan a path given start and goal in world map
   * @param start     start in world map
   * @param goal      goal in world map
   * @param plan      plan
   * @param tolerance error tolerance
   * @return true if find a path successfully, else false
   */
  bool makePlan(const rmp::common::geometry::Point3d& start, const rmp::common::geometry::Point3d& goal,
                double tolerance, rmp::common::geometry::Points3d& plan);

  /**
   * @brief Regeister planning service
   * @param req  request from client
   * @param resp response to server
   */
  void makePlanService(const std::shared_ptr<nav_msgs::srv::GetPlan::Request> req,
                       std::shared_ptr<nav_msgs::srv::GetPlan::Response> resp);

  /**
   * @brief Calculate plan from planning path
   * @param path path generated by global planner
   * @param plan plan transfromed from path, i.e. [start, ..., goal]
   * @return bool true if successful, else false
   */
  bool getPlanFromPath(PathPlanner::Points3d& path, std::vector<geometry_msgs::msg::PoseStamped>& plan);

  /**
   * @brief Prunes the global path to remove portions that the robot has already passed
   * @param robot_pose the current pose of the robot
   * @param path       the global path to be pruned
   * @return true if pruning is successful, false otherwise
   */
  static bool prune(const PathPlanner::Point3d& robot_pose, PathPlanner::Points3d& path);

protected:
  bool initialized_;                        // initialization flag
  rclcpp::Node::SharedPtr node_;            // ROS node
  nav2_costmap_2d::Costmap2DROS* costmap_ros_;   // costmap(ROS wrapper)
  std::string frame_id_;                    // costmap frame ID
  PLANNER_TYPE planner_type_;               // planner type
  std::shared_ptr<PathPlanner> g_planner_;  // global path planner
  rclcpp::Publisher<nav_msgs::msg::Path>::SharedPtr plan_pub_;                    // path planning publisher
  rclcpp::Publisher<nav_msgs::msg::OccupancyGrid>::SharedPtr expand_pub_;         // nodes explorer publisher
  rclcpp::Publisher<visualization_msgs::msg::Marker>::SharedPtr random_tree_pub_; // random search tree publisher
  rclcpp::Publisher<visualization_msgs::msg::Marker>::SharedPtr roadmap_pub_;     // roadmap publisher
  rclcpp::Publisher<visualization_msgs::msg::Marker>::SharedPtr particles_pub_;   // evolutionary particles publisher
  rclcpp::Service<nav_msgs::srv::GetPlan>::SharedPtr make_plan_srv_;              // planning service

private:
  bool is_outline_;        // whether outline the boudary of map
  bool is_expand_;         // whether publish expand map or not
  double tolerance_;       // tolerance
  bool enable_resample_;   // whether enable path resample
  double resample_ratio_;  // path resample ratio
};
}  // namespace path_planner
}  // namespace rmp
#endif
